// ─── Instance statusline (claude) ──────────────────────────────────────
// Every prepared instance settings.json carries a generated statusLine whose
// command is a per-instance wrapper script. The wrapper prints the provider
// name first, then relays whatever the user's GLOBAL statusLine (~/.claude/
// settings.json — claude-hud, ccstatusline, anything) renders, passing the
// statusline JSON from Claude Code through untouched. The global tool stays
// the single source of truth for how the rest of the line looks; the provider
// tag is the only thing switch adds.
//
// The injection lives ONLY in the instance copy: the wrapper script is
// written into the instance dir and the statusLine entry is regenerated on
// every prepare — it is never written back into the cc-switch DB, because
// statusLine is a channel-owned path (isStatusLineChannelPath): the overwrite
// guard ignores it and the upward settings sync yields it, exactly like the
// plugin channel.

const STATUSLINE_WRAPPER_FILENAME = "statusline-wrapper.mjs";

// [C6 for the statusline channel] — the settings-field sync and the
// overwrite guard must neither report nor vote on this subtree.
function isStatusLineChannelPath(path) {
  return path === "statusLine" || path.startsWith("statusLine.");
}

function claudeProviderName(providerId) {
  try {
    return queryProviderById(providerId, "claude")?.name || providerId;
  } catch {
    return providerId; // DB hiccup — the id still identifies the instance
  }
}

// Single-quote for /bin/sh; paths only ever get safer under this.
function shQuote(path) {
  return `'${path.replace(/'/g, "'\\''")}'`;
}

function buildStatusLineWrapperScript(providerName, globalSettingsPath, relayCommand, colorCode = "auto", usageConfig = null, stackConfig = null) {
  // Aggregation instances retarget the tag at runtime (ccs key → member
  // name), so their tag is a function of the live model id; the single-
  // provider shape below stays a constant expression — byte-identical to the
  // pre-aggregation wrapper, a guarantee the regression tests assert on.
  const tagLines = stackConfig
    ? [
      `function makeTag(name) {`,
      `  let h = 2166136261;`,
      `  for (const ch of name) { h ^= ch.codePointAt(0); h = Math.imul(h, 16777619) >>> 0; }`,
      `  const c = COLOR === "auto" ? PALETTE[h % PALETTE.length] : parseInt(COLOR, 10);`,
      `  return "\\x1b[1m\\x1b[" + c + "m[" + name + "]\\x1b[0m";`,
      `}`,
      `let tag = makeTag(PROVIDER);`,
    ]
    : [
      `let hash = 2166136261;`,
      `for (const ch of PROVIDER) { hash ^= ch.codePointAt(0); hash = Math.imul(hash, 16777619) >>> 0; }`,
      `const code = COLOR === "auto" ? PALETTE[hash % PALETTE.length] : parseInt(COLOR, 10);`,
      `const tag = "\\x1b[1m\\x1b[" + code + "m[" + PROVIDER + "]\\x1b[0m";`,
    ];
  return [
    `#!/usr/bin/env node`,
    `// Generated by cc-switch-parallel — do not edit; regenerated on every launch.`,
    `// Instance statusline: prints the provider name, then relays the user's`,
    `// statusline tool (claude-hud, ccstatusline, …) after it, passing the`,
    `// statusline JSON from Claude Code through untouched.`,
    `import { spawnSync } from "node:child_process";`,
    `import { readFileSync } from "node:fs";`,
    `const PROVIDER = ${JSON.stringify(providerName)};`,
    `const SELF_MARKER = ${JSON.stringify(STATUSLINE_WRAPPER_FILENAME)};`,
    `const GLOBAL_SETTINGS = ${JSON.stringify(globalSettingsPath)};`,
    `// Explicit statusLine from the cc-switch config (inlined at generation`,
    `// time) — takes precedence over the global settings.json fallback.`,
    `const RELAY_COMMAND = ${JSON.stringify(relayCommand || null)};`,
    `// Tag color: "auto" hashes the provider name (FNV-1a over the bright`,
    `// palette); any ANSI classic code (30-37 / 90-97) is used verbatim.`,
    `const COLOR = ${JSON.stringify(isValidStatuslineColor(colorCode) ? colorCode : "auto")};`,
    ``,
    `const PALETTE = [96, 92, 93, 95, 94, 91];`,
    ...tagLines,
    ``,
    `let input = "";`,
    `try { input = readFileSync(0, "utf8"); } catch {}`,
    ``,
    `// Relay the user's statusline: the inlined RELAY_COMMAND (from the`,
    `// cc-switch config) wins; otherwise fall back to the global`,
    `// ~/.claude/settings.json — and never relay this wrapper itself (loop`,
    `// guard). Detached refresh mode (CC_LAUNCH_USAGE_REFRESH=1, spawned by`,
    `// the usage tail below) only fetches and exits — skip the relay so a`,
    `// background refresh never re-runs the user's statusline tool on empty`,
    `// stdin (wasted run, side effects, up to the 4s relay timeout before`,
    `// the fetch even starts).`,
    `let relayed = "";`,
    `try {`,
    `  if (process.env.CC_LAUNCH_USAGE_REFRESH !== "1") {`,
    `    let cmd = RELAY_COMMAND || "";`,
    `    if (!cmd) {`,
    `      const sl = JSON.parse(readFileSync(GLOBAL_SETTINGS, "utf8")).statusLine;`,
    `      cmd = sl && sl.type === "command" && typeof sl.command === "string" ? sl.command.trim() : "";`,
    `    }`,
    `    if (cmd && !cmd.includes(SELF_MARKER)) {`,
    `      const r = spawnSync("/bin/sh", ["-c", cmd], { input, encoding: "utf8", timeout: 4000 });`,
    `      if (r.stdout && r.stdout.trim()) relayed = r.stdout;`,
    `    }`,
    `  }`,
    `} catch {}`,
    ``,
    `// Placement: when the relayed line LEADS with the model indicator (e.g.`,
    `// claude-hud's "[Opus] │ …", possibly behind its own ANSI codes or`,
    `// leading indent), glue the tag in front of it — [provider][model]. The`,
    `// lead check runs on an ANSI-stripped view and walks back over ALL`,
    `// non-alphanumeric characters, so indent or codes before the "[" don't`,
    `// break it; a mid-line model stops at the preceding word and falls back.`,
    `// Anywhere else the tag sits at the start of the line with a space —`,
    `// visible first, never mangling the relayed text.`,
    `let dn = "";`,
    `try { dn = JSON.parse(input)?.model?.display_name || ""; } catch {}`,
    ``,
    `const lines = relayed.replace(/\\n+$/, "").split("\\n");`,
    `const line0 = lines[0] || "";`,
    `let glue = false;`,
    `if (line0 && dn) {`,
    `  const text = line0.replace(/\\x1b\\[[0-9;]*m/g, "");`,
    `  const i = text.indexOf(dn);`,
    `  if (i > 0) {`,
    `    let j = i;`,
    `    while (j > 0 && !/[0-9A-Za-z]/.test(text[j - 1])) j--;`,
    `    glue = j === 0;`,
    `  }`,
    `}`,
    // With a resolved usage identity the whole tail — imports, usage
    // runtime, and line composition — comes from buildUsageWrapperLines;
    // without one, these four lines are byte-identical to the pre-usage
    // wrapper (a hard guarantee the tests assert on). Aggregation instances
    // take the stack-aware tail instead (ccs-key decode + per-member map).
    ...(stackConfig
      ? buildStackUsageWrapperLines(stackConfig)
      : usageConfig
        ? buildUsageWrapperLines(usageConfig)
        : [
          `const first = glue`,
          `  ? tag + line0.replace(/^\\s+/, "") // drop the relay's leading indent`,
          `  : tag + (line0 ? " " + line0 : "");`,
          `process.stdout.write([first].concat(lines.slice(1)).join("\\n") + "\\n");`,
        ]),
  ].join("\n");
}

// Tail of the wrapper script when a usage identity was resolved: the USAGE
// runtime (cache read/write, fetch, parse, claude-hud-style rendering,
// context-segment insertion) plus the usage-aware composition of the first
// line. Runs cache-first with stale-while-revalidate: a fresh TTL hit renders
// with zero network, a stale cache renders last-known values while a
// detached self-spawn refreshes in the background, and only the very first
// render (no cache at all) pays one short sync fetch — failures stay silent
// and leave the statusline byte-identical to the no-usage shape.
function buildUsageWrapperLines(usageConfig) {
  return [
    `// ─── Provider usage segment (generated by cc-switch-parallel) ────────`,
    `import { spawn } from "node:child_process";`,
    `import { writeFileSync, renameSync } from "node:fs";`,
    `const USAGE = ${JSON.stringify(usageConfig)};`,
    ``,
    `function usageReadCache() {`,
    `  try {`,
    `    const c = JSON.parse(readFileSync(USAGE.cachePath, "utf8"));`,
    `    // A failure-only cache ({data:null, errTs}) is still a valid cache read:`,
    `    // dropping it here made backedOff permanently false, so every render paid`,
    `    // a fresh sync fetch. Only the kind check applies when data exists.`,
    `    if (c && c.v === 1 && (!c.data || c.data.kind === USAGE.kind)) return c;`,
    `  } catch {}`,
    `  return null;`,
    `}`,
    ``,
    `// tmp + rename, mirroring the launcher's atomicWrite; racy double-writes`,
    `// from overlapping renders are harmless (equivalent content).`,
    `function usageWriteCache(fields) {`,
    `  try {`,
    `    let cur = {};`,
    `    try { cur = JSON.parse(readFileSync(USAGE.cachePath, "utf8")) || {}; } catch {}`,
    `    const merged = { v: 1, ts: 0, refreshTs: 0, errTs: 0, data: null, ...cur, ...fields };`,
    `    // Unique tmp name: concurrent renders AND the detached refresh may write`,
    `    // the same cache at once; a shared "<cache>.tmp" let them rename each`,
    `    // other's half-written files.`,
    `    const tmp = USAGE.cachePath + ".tmp." + process.pid + "." + Math.random().toString(36).slice(2);`,
    `    writeFileSync(tmp, JSON.stringify(merged));`,
    `    renameSync(tmp, USAGE.cachePath);`,
    `  } catch {}`,
    `}`,
    ``,
    `function usageParse(body) {`,
    `  try {`,
    `    if (USAGE.kind === "zhipu") {`,
    `      if (body && body.success === false) return null; // business-level error (e.g. code 401 token rejected)`,
    `      // zhipu wraps the payload: {"code":200,"data":{"limits":[...]}}`,
    `      const payload = body && body.data && typeof body.data === "object" ? body.data : body;`,
    `      const limits = Array.isArray(payload && payload.limits) ? payload.limits : [];`,
    `      const pct = (l) => Math.max(0, Math.min(100, Math.round(Number(l && l.percentage) || 0)));`,
    `      let five = null;`,
    `      let weekly = null;`,
    `      for (const l of limits) {`,
    `        if (!l || l.type !== "TOKENS_LIMIT") continue;`,
    `        if (l.unit === 3 && l.number === 5) five = pct(l);`,
    `        else if (l.unit === 6 && l.number === 1) weekly = pct(l);`,
    `      }`,
    `      if (five === null) return null;`,
    `      return { kind: "zhipu", fiveH: five, weekly };`,
    `    }`,
    `    if (USAGE.kind === "deepseek") {`,
    `      const infos = Array.isArray(body && body.balance_infos) ? body.balance_infos : [];`,
    `      const info = infos[0];`,
    `      const bal = info && typeof info.total_balance === "string" ? info.total_balance.trim() : "";`,
    `      if (!bal) return null;`,
    `      const currency = info.currency || "";`,
    `      const sym = { USD: "$", CNY: "¥" }[currency] || "";`,
    `      return { kind: "deepseek", balance: bal, currency, sym };`,
    `    }`,
    `  } catch {}`,
    `  return null;`,
    `}`,
    ``,
    `async function usageFetch(timeoutMs) {`,
    `  try {`,
    `    const headers = { "Content-Type": "application/json" };`,
    `    headers.Authorization = USAGE.authStyle === "bearer" ? "Bearer " + USAGE.token : USAGE.token;`,
    `    if (USAGE.kind === "zhipu") headers["Accept-Language"] = "en-US,en";`,
    `    const res = await fetch(USAGE.url, { headers, signal: AbortSignal.timeout(timeoutMs) });`,
    `    if (!res.ok) return null;`,
    `    return usageParse(await res.json());`,
    `  } catch {}`,
    `  return null;`,
    `}`,
    ``,
    `function usageBar(pct, width, color) {`,
    `  const w = Math.max(3, Math.min(20, width));`,
    `  const fill = Math.max(0, Math.min(w, Math.round((pct / 100) * w)));`,
    `  return color + "█".repeat(fill) + "\\x1b[0m" + "\\x1b[2m" + "░".repeat(w - fill) + "\\x1b[0m";`,
    `}`,
    ``,
    `// claude-hud bar style: "5h ███░░░ 40% · W ████░░ 52%" / deepseek "[$12.34]".`,
    `// Fill and pct share the threshold color (<70 green, 70-89 yellow, >=90`,
    `// red); empty bar cells stay dim. A window at 100% (post-clamp/round, so`,
    `// raw >=99.5) drops bar and pct for a red "⚠ Limit" — 5h and W judged`,
    `// independently. DeepSeek balance: <10 bright red, <20 bright yellow,`,
    `// else bright white (hardcoded, currency-agnostic; unparsable falls back`,
    `// to white). The bar width follows the anchored context line's own bar.`,
    `// The window separator is DETECTED, not hardcoded: the relay's own`,
    `// segment separator (│, then |) is reused so the cells blend into the`,
    `// surrounding statusline; " · " is only the standalone default when no`,
    `// separator exists to mirror.`,
    `function usageBarWidth(relayLine) {`,
    `  const bar = (relayLine || "").replace(/\\x1b\\[[0-9;]*m/g, "").match(/[█▓▒░]{3,}/);`,
    `  return bar ? bar[0].length : 6;`,
    `}`,
    `function usageSegmentText(data, barWidth, innerSep) {`,
    `  const dim = "\\x1b[2m";`,
    `  const off = "\\x1b[0m";`,
    `  if (data.kind === "zhipu") {`,
    `    const color = (p) => (p >= 90 ? "\\x1b[91m" : p >= 70 ? "\\x1b[93m" : "\\x1b[32m");`,
    `    const cell = (label, p) =>`,
    `      p >= 100 ? dim + label + " " + off + "\\x1b[91m⚠ Limit" + off :`,
    `        dim + label + " " + off + usageBar(p, barWidth, color(p)) + color(p) + " " + p + "%" + off;`,
    `    let t = cell("5h", data.fiveH);`,
    `    if (data.weekly !== null && data.weekly !== undefined) t += dim + innerSep + off + cell("W", data.weekly);`,
    `    return t;`,
    `  }`,
    `  if (data.kind === "deepseek") {`,
    `    const amount = data.sym ? data.sym + data.balance : data.balance + (data.currency ? " " + data.currency : "");`,
    `    const n = parseFloat(data.balance);`,
    `    const bal = Number.isNaN(n) ? "\\x1b[97m" : n < 10 ? "\\x1b[91m" : n < 20 ? "\\x1b[93m" : "\\x1b[97m";`,
    `    return dim + "[" + off + bal + amount + off + dim + "]" + off;`,
    `  }`,
    `  return "";`,
    `}`,
    ``,
    `// Splice the usage segment after the relay line's context segment.`,
    `// claude-hud joins segments with " │ " (some tools use "|"); the split`,
    `// keeps the separators so the original spacing survives, and the usage`,
    `// cell reuses the separator style of the line it lands in.`,
    `// A segment counts as "context" only when the word co-occurs with a`,
    `// quota indicator (a percentage or a bar) IN THE SAME segment — git`,
    `// branches, paths and window titles routinely carry the word itself:`,
    `// a branch named fix/usage-context-line-and-separator once hijacked`,
    `// the anchor and pushed the usage row above the real context row.`,
    `function isContextSegment(stripped) {`,
    `  return /(context|ctx|上下文)/i.test(stripped) && /(\\d+(?:\\.\\d+)?\\s*%|[█▓▒░]{3,})/.test(stripped);`,
    `}`,
    `function usageInsertIntoLine(line, usageText) {`,
    `  const strippedOf = (s) => s.replace(/\\x1b\\[[0-9;]*m/g, "");`,
    `  for (const sep of ["│", "|"]) {`,
    `    if (!line.includes(sep)) continue;`,
    `    const parts = line.split(new RegExp("(" + (sep === "|" ? "\\\\|" : sep) + ")"));`,
    `    for (let i = 0; i < parts.length; i += 2) {`,
    `      if (isContextSegment(strippedOf(parts[i]))) {`,
    `        parts.splice(i + 2, 0, " " + usageText + " ", parts[i + 1] || sep);`,
    `        return parts.join("");`,
    `      }`,
    `    }`,
    `  }`,
    `  return "";`,
    `}`,
    ``,
    `let usageData = null;`,
    `if (process.env.CC_LAUNCH_USAGE_REFRESH === "1") {`,
    `  // Detached refresh mode: fetch with the long timeout, persist, exit.`,
    `  // Several renders can spawn this at once; skip the request when the cache`,
    `  // is already fresh or the failure backoff is still active.`,
    `  const now = Date.now();`,
    `  const cache = usageReadCache();`,
    `  const fresh = cache && cache.data && now - cache.ts < USAGE.ttlMs;`,
    `  const backedOff = !!(cache && cache.errTs && now - cache.errTs < USAGE.errorBackoffMs);`,
    `  if (!fresh && !backedOff) {`,
    `    const ok = await usageFetch(USAGE.refreshTimeoutMs);`,
    `    usageWriteCache(ok`,
    `      ? { ts: Date.now(), refreshTs: Date.now(), errTs: 0, data: ok }`,
    `      : { refreshTs: Date.now(), errTs: Date.now() });`,
    `  }`,
    `  process.exit(0);`,
    `}`,
    `{`,
    `  const now = Date.now();`,
    `  const cache = usageReadCache();`,
    `  const fresh = cache && cache.data && now - cache.ts < USAGE.ttlMs;`,
    `  const backedOff = !!(cache && cache.errTs && now - cache.errTs < USAGE.errorBackoffMs);`,
    `  const deduped = !!(cache && cache.refreshTs && now - cache.refreshTs <= USAGE.refreshDedupMs);`,
    `  if (fresh) usageData = cache.data;`,
    `  else if (cache && cache.data) {`,
    `    usageData = cache.data; // stale — show last known, refresh in background`,
    `    if (!backedOff && !deduped) {`,
    `      usageWriteCache({ refreshTs: now });`,
    `      try {`,
    `        spawn(process.execPath, [USAGE.selfPath], {`,
    `          detached: true,`,
    `          stdio: "ignore",`,
    `          env: { ...process.env, CC_LAUNCH_USAGE_REFRESH: "1" },`,
    `        }).unref();`,
    `      } catch {}`,
    `    }`,
    `  } else if (!backedOff && !deduped) {`,
    `    usageData = await usageFetch(USAGE.syncTimeoutMs);`,
    `    if (usageData) usageWriteCache({ ts: now, refreshTs: now, errTs: 0, data: usageData });`,
    `    else usageWriteCache({ refreshTs: now, errTs: now });`,
    `  }`,
    `}`,
    `// Anchor at the FIRST relayed line carrying a context segment — claude-hud`,
    `// renders context on its own row BELOW the model/git line, so scanning`,
    `// line 0 alone would fall back to the tail and land BEFORE the context.`,
    `// No anchor anywhere → tail of line 0; empty relay → the bare tag line.`,
    `if (usageData) {`,
    `  const innerSep = relayed.indexOf("│") >= 0 ? " │ " : relayed.indexOf("|") >= 0 ? " | " : " · ";`,
    `  const stripA = (s) => s.replace(/\\x1b\\[[0-9;]*m/g, "");`,
    `  let anchorIdx = -1;`,
    `  for (let i = 0; i < lines.length; i++) {`,
    `    if (lines[i] && isContextSegment(stripA(lines[i]))) { anchorIdx = i; break; }`,
    `  }`,
    `  if (anchorIdx >= 0) {`,
    `    const text = usageSegmentText(usageData, usageBarWidth(lines[anchorIdx]), innerSep);`,
    `    // anchor rows often have no segment separator of their own (claude-hud`,
    `    // renders context bare) — still JOIN with the detected separator so the`,
    `    // cell reads as part of the same line, never a bare space`,
    `    lines[anchorIdx] = usageInsertIntoLine(lines[anchorIdx], text) || (lines[anchorIdx] + innerSep + text);`,
    `  } else if (lines[0]) {`,
    `    lines[0] += innerSep + usageSegmentText(usageData, 6, innerSep);`,
    `  } else {`,
    `    lines[0] = usageSegmentText(usageData, 6, innerSep);`,
    `  }`,
    `}`,
    `const first = glue`,
    `  ? tag + lines[0].replace(/^\\s+/, "") // drop the relay's leading indent`,
    `  : tag + (lines[0] ? " " + lines[0] : "");`,
    `process.stdout.write([first].concat(lines.slice(1)).join("\\n") + "\\n");`,
  ];
}

// Tail of the wrapper for AGGREGATION instances (cc-switch 4.0 Stack): the
// usage runtime is parameterized over a per-member config map instead of the
// single inlined USAGE. At render time the ccs key is decoded from the
// statusline model id ("ccs-claude-<key>--<model>[1m]" — key never contains
// "--", so the FIRST separator splits it; the id is lowercase but keys are
// lowercase by construction anyway). Routing: decoded key in map → that
// member; no ccs prefix → the default provider's key (upstream routes
// prefix-less requests there); decoded-but-unregistered or empty map → the
// side-by-side fallback: render every member's last-known cell and refresh
// them in the background. Cache/SWR semantics per member mirror the
// single-provider tail (fresh hit = zero network, stale = last-known +
// detached refresh, no cache = one sync fetch), each in its own cache file.
function buildStackUsageWrapperLines(stackConfig) {
  return [
    `// ─── Aggregation usage segment (cc-switch Stack) ────────────────────`,
    `import { spawn } from "node:child_process";`,
    `import { writeFileSync, renameSync } from "node:fs";`,
    `const STACK = ${JSON.stringify(stackConfig)};`,
    ``,
    `function cfgReadCache(cfg) {`,
    `  try {`,
    `    const c = JSON.parse(readFileSync(cfg.cachePath, "utf8"));`,
    `    // Same failure-cache rule as usageReadCache: keep {data:null, errTs}`,
    `    // readable so the backoff check can see it.`,
    `    if (c && c.v === 1 && (!c.data || c.data.kind === cfg.kind)) return c;`,
    `  } catch {}`,
    `  return null;`,
    `}`,
    ``,
    `function cfgWriteCache(cfg, fields) {`,
    `  try {`,
    `    let cur = {};`,
    `    try { cur = JSON.parse(readFileSync(cfg.cachePath, "utf8")) || {}; } catch {}`,
    `    const merged = { v: 1, ts: 0, refreshTs: 0, errTs: 0, data: null, ...cur, ...fields };`,
    `    const tmp = cfg.cachePath + ".tmp." + process.pid + "." + Math.random().toString(36).slice(2);`,
    `    writeFileSync(tmp, JSON.stringify(merged));`,
    `    renameSync(tmp, cfg.cachePath);`,
    `  } catch {}`,
    `}`,
    ``,
    `function usageParse(body, kind) {`,
    `  try {`,
    `    if (kind === "zhipu") {`,
    `      if (body && body.success === false) return null;`,
    `      const payload = body && body.data && typeof body.data === "object" ? body.data : body;`,
    `      const limits = Array.isArray(payload && payload.limits) ? payload.limits : [];`,
    `      const pct = (l) => Math.max(0, Math.min(100, Math.round(Number(l && l.percentage) || 0)));`,
    `      let five = null;`,
    `      let weekly = null;`,
    `      for (const l of limits) {`,
    `        if (!l || l.type !== "TOKENS_LIMIT") continue;`,
    `        if (l.unit === 3 && l.number === 5) five = pct(l);`,
    `        else if (l.unit === 6 && l.number === 1) weekly = pct(l);`,
    `      }`,
    `      if (five === null) return null;`,
    `      return { kind: "zhipu", fiveH: five, weekly };`,
    `    }`,
    `    if (kind === "deepseek") {`,
    `      const infos = Array.isArray(body && body.balance_infos) ? body.balance_infos : [];`,
    `      const info = infos[0];`,
    `      const bal = info && typeof info.total_balance === "string" ? info.total_balance.trim() : "";`,
    `      if (!bal) return null;`,
    `      const currency = info.currency || "";`,
    `      const sym = { USD: "$", CNY: "¥" }[currency] || "";`,
    `      return { kind: "deepseek", balance: bal, currency, sym };`,
    `    }`,
    `  } catch {}`,
    `  return null;`,
    `}`,
    ``,
    `async function usageFetch(cfg, timeoutMs) {`,
    `  try {`,
    `    const headers = { "Content-Type": "application/json" };`,
    `    headers.Authorization = cfg.authStyle === "bearer" ? "Bearer " + cfg.token : cfg.token;`,
    `    if (cfg.kind === "zhipu") headers["Accept-Language"] = "en-US,en";`,
    `    const res = await fetch(cfg.url, { headers, signal: AbortSignal.timeout(timeoutMs) });`,
    `    if (!res.ok) return null;`,
    `    return usageParse(await res.json(), cfg.kind);`,
    `  } catch {}`,
    `  return null;`,
    `}`,
    ``,
    `function usageBar(pct, width, color) {`,
    `  const w = Math.max(3, Math.min(20, width));`,
    `  const fill = Math.max(0, Math.min(w, Math.round((pct / 100) * w)));`,
    `  return color + "█".repeat(fill) + "\\x1b[0m" + "\\x1b[2m" + "░".repeat(w - fill) + "\\x1b[0m";`,
    `}`,
    ``,
    `function usageBarWidth(relayLine) {`,
    `  const bar = (relayLine || "").replace(/\\x1b\\[[0-9;]*m/g, "").match(/[█▓▒░]{3,}/);`,
    `  return bar ? bar[0].length : 6;`,
    `}`,
    ``,
    `function usageSegmentText(data, barWidth, innerSep) {`,
    `  const dim = "\\x1b[2m";`,
    `  const off = "\\x1b[0m";`,
    `  if (data.kind === "zhipu") {`,
    `    const color = (p) => (p >= 90 ? "\\x1b[91m" : p >= 70 ? "\\x1b[93m" : "\\x1b[32m");`,
    `    const cell = (label, p) =>`,
    `      p >= 100 ? dim + label + " " + off + "\\x1b[91m⚠ Limit" + off :`,
    `        dim + label + " " + off + usageBar(p, barWidth, color(p)) + color(p) + " " + p + "%" + off;`,
    `    let t = cell("5h", data.fiveH);`,
    `    if (data.weekly !== null && data.weekly !== undefined) t += dim + innerSep + off + cell("W", data.weekly);`,
    `    return t;`,
    `  }`,
    `  if (data.kind === "deepseek") {`,
    `    const amount = data.sym ? data.sym + data.balance : data.balance + (data.currency ? " " + data.currency : "");`,
    `    const n = parseFloat(data.balance);`,
    `    const bal = Number.isNaN(n) ? "\\x1b[97m" : n < 10 ? "\\x1b[91m" : n < 20 ? "\\x1b[93m" : "\\x1b[97m";`,
    `    return dim + "[" + off + bal + amount + off + dim + "]" + off;`,
    `  }`,
    `  return "";`,
    `}`,
    ``,
    `function isContextSegment(stripped) {`,
    `  return /(context|ctx|上下文)/i.test(stripped) && /(\\d+(?:\\.\\d+)?\\s*%|[█▓▒░]{3,})/.test(stripped);`,
    `}`,
    ``,
    `function usageInsertIntoLine(line, usageText) {`,
    `  const strippedOf = (s) => s.replace(/\\x1b\\[[0-9;]*m/g, "");`,
    `  for (const sep of ["│", "|"]) {`,
    `    if (!line.includes(sep)) continue;`,
    `    const parts = line.split(new RegExp("(" + (sep === "|" ? "\\\\|" : sep) + ")"));`,
    `    for (let i = 0; i < parts.length; i += 2) {`,
    `      if (isContextSegment(strippedOf(parts[i]))) {`,
    `        parts.splice(i + 2, 0, " " + usageText + " ", parts[i + 1] || sep);`,
    `        return parts.join("");`,
    `      }`,
    `    }`,
    `  }`,
    `  return "";`,
    `}`,
    ``,
    `// Decode the member key from the statusline model id. Aggregated ids look`,
    `// like "ccs-claude-deepseek--deepseek-flash[1m]" — the key never contains`,
    `// "--" (upstream key slug rule), so the FIRST separator ends it and the`,
    `// model part may freely contain further dashes or slashes.`,
    `let modelId = "";`,
    `try { const m = JSON.parse(input)?.model; modelId = String((m && (m.id || m.display_name)) || ""); } catch {}`,
    `const ccsMatch = modelId.match(/^ccs-claude-([a-z0-9-]+?)--/i);`,
    `let activeKey = null;`,
    `if (ccsMatch) {`,
    `  const k = ccsMatch[1].toLowerCase();`,
    `  if (STACK.map[k]) activeKey = k;`,
    `} else if (STACK.defaultKey && STACK.map[STACK.defaultKey]) {`,
    `  activeKey = STACK.defaultKey;`,
    `}`,
    `// Tag follows the billable member, not the launch provider.`,
    `if (activeKey && STACK.names[activeKey]) tag = makeTag(STACK.names[activeKey]);`,
    ``,
    `if (process.env.CC_LAUNCH_USAGE_REFRESH === "1") {`,
    `  // Detached refresh mode: KEYS narrows to the members the parent marked`,
    `  // (single-key KEY kept for compatibility), absent/unknown → all.`,
    `  const only = process.env.CC_LAUNCH_USAGE_REFRESH_KEY;`,
    `  const listed = String(process.env.CC_LAUNCH_USAGE_REFRESH_KEYS || "")`,
    `    .split(",").map((s) => s.trim()).filter((k) => STACK.map[k]);`,
    `  const keys = listed.length ? listed : only && STACK.map[only] ? [only] : Object.keys(STACK.map);`,
    `  const now = Date.now();`,
    `  for (const k of keys) {`,
    `    const cfg = STACK.map[k];`,
    `    const cache = cfgReadCache(cfg);`,
    `    const fresh = cache && cache.data && now - cache.ts < cfg.ttlMs;`,
    `    const backedOff = !!(cache && cache.errTs && now - cache.errTs < cfg.errorBackoffMs);`,
    `    // Do NOT check refreshTs here — the parent wrote it just before spawn.`,
    `    if (fresh || backedOff) continue;`,
    `    const ok = await usageFetch(cfg, cfg.refreshTimeoutMs);`,
    `    cfgWriteCache(cfg, ok`,
    `      ? { ts: Date.now(), refreshTs: Date.now(), errTs: 0, data: ok }`,
    `      : { refreshTs: Date.now(), errTs: Date.now() });`,
    `  }`,
    `  process.exit(0);`,
    `}`,
    ``,
    `let usageData = null; // one data object, or an array for the side-by-side form`,
    `{`,
    `  const now = Date.now();`,
    `  const stackKeys = Object.keys(STACK.map);`,
    `  if (activeKey) {`,
    `    const cfg = STACK.map[activeKey];`,
    `    const cache = cfgReadCache(cfg);`,
    `    const fresh = cache && cache.data && now - cache.ts < cfg.ttlMs;`,
    `    const backedOff = !!(cache && cache.errTs && now - cache.errTs < cfg.errorBackoffMs);`,
    `    const deduped = !!(cache && cache.refreshTs && now - cache.refreshTs <= cfg.refreshDedupMs);`,
    `    if (fresh) usageData = { key: activeKey, data: cache.data };`,
    `    else if (cache && cache.data) {`,
    `      usageData = { key: activeKey, data: cache.data }; // stale — show last known, refresh in background`,
    `      if (!backedOff && !deduped) {`,
    `        cfgWriteCache(cfg, { refreshTs: now });`,
    `        try {`,
    `          spawn(process.execPath, [STACK.selfPath], {`,
    `            detached: true,`,
    `            stdio: "ignore",`,
    `            env: { ...process.env, CC_LAUNCH_USAGE_REFRESH: "1", CC_LAUNCH_USAGE_REFRESH_KEY: activeKey },`,
    `          }).unref();`,
    `        } catch {}`,
    `      }`,
    `    } else if (!backedOff && !deduped) {`,
    `      const fetched = await usageFetch(cfg, cfg.syncTimeoutMs);`,
    `      if (fetched) {`,
    `        usageData = { key: activeKey, data: fetched };`,
    `        cfgWriteCache(cfg, { ts: now, refreshTs: now, errTs: 0, data: fetched });`,
    `      } else cfgWriteCache(cfg, { refreshTs: now, errTs: now });`,
    `    }`,
    `  } else if (stackKeys.length) {`,
    `    // Side-by-side fallback (model not attributable to any member): render`,
    `    // every member's last-known cell with its key as a dim prefix — the`,
    `    // cells are meaningless without knowing whose quota/balance they are —`,
    `    // no sync fetch, background refresh (marked members only) so the next`,
    `    // pass has data. Each member is checked independently: a failed member`,
    `    // stays in error backoff and MUST NOT trigger a fresh spawn on every`,
    `    // render (its ts stays 0 forever, which used to make anyMissing true).`,
    `    const cells = [];`,
    `    const refreshKeys = [];`,
    `    for (const k of stackKeys) {`,
    `      const cfg = STACK.map[k];`,
    `      const cache = cfgReadCache(cfg);`,
    `      if (cache && cache.data) cells.push({ key: k, data: cache.data });`,
    `      const fresh = cache && cache.data && now - cache.ts < cfg.ttlMs;`,
    `      const backedOff = !!(cache && cache.errTs && now - cache.errTs < cfg.errorBackoffMs);`,
    `      const deduped = !!(cache && cache.refreshTs && now - cache.refreshTs <= cfg.refreshDedupMs);`,
    `      if (!fresh && !backedOff && !deduped) refreshKeys.push(k);`,
    `    }`,
    `    if (cells.length) usageData = cells;`,
    `    if (refreshKeys.length) {`,
    `      for (const k of refreshKeys) cfgWriteCache(STACK.map[k], { refreshTs: now });`,
    `      try {`,
    `        spawn(process.execPath, [STACK.selfPath], {`,
    `          detached: true,`,
    `          stdio: "ignore",`,
    `          env: { ...process.env, CC_LAUNCH_USAGE_REFRESH: "1", CC_LAUNCH_USAGE_REFRESH_KEYS: refreshKeys.join(",") },`,
    `        }).unref();`,
    `      } catch {}`,
    `    }`,
    `  }`,
    `}`,
    `if (usageData) {`,
    `  const multi = Array.isArray(usageData); // side-by-side form carries keys`,
    `  const cells = multi ? usageData : [usageData];`,
    `  const innerSep = relayed.indexOf("│") >= 0 ? " │ " : relayed.indexOf("|") >= 0 ? " | " : " · ";`,
    `  const stripA = (s) => s.replace(/\\x1b\\[[0-9;]*m/g, "");`,
    `  let anchorIdx = -1;`,
    `  for (let i = 0; i < lines.length; i++) {`,
    `    if (lines[i] && isContextSegment(stripA(lines[i]))) { anchorIdx = i; break; }`,
    `  }`,
    `  // attributed (single) form renders bare; the side-by-side form prefixes`,
    `  // each cell with its member key (dim) — the stable ccs id segment, not`,
    `  // the user-editable provider name`,
    `  const dim = "\\x1b[2m";`,
    `  const off = "\\x1b[0m";`,
    `  const renderCells = (barWidth) => cells.map((c) => {`,
    `    const text = usageSegmentText(c.data, barWidth, innerSep);`,
    `    return multi ? dim + c.key + off + " " + text : text;`,
    `  }).join(innerSep);`,
    `  if (anchorIdx >= 0) {`,
    `    const text = renderCells(usageBarWidth(lines[anchorIdx]));`,
    `    lines[anchorIdx] = usageInsertIntoLine(lines[anchorIdx], text) || (lines[anchorIdx] + innerSep + text);`,
    `  } else if (lines[0]) {`,
    `    lines[0] += innerSep + renderCells(6);`,
    `  } else {`,
    `    lines[0] = renderCells(6);`,
    `  }`,
    `}`,
    `const first = glue`,
    `  ? tag + lines[0].replace(/^\\s+/, "") // drop the relay's leading indent`,
    `  : tag + (lines[0] ? " " + lines[0] : "");`,
    `process.stdout.write([first].concat(lines.slice(1)).join("\\n") + "\\n");`,
  ];
}

// Regenerate the wrapper script + statusLine entry inside `effective`.
// instanceDir is re-derived from providerId (same expression as
// setupClaudeInstance) because the guard's computeEffectiveSettings [C3]
// path has no instanceDir argument — both call sites must land on the same
// wrapper path for the derivations to compare equal. settingsConfig and
// meta feed the usage identity the same way: both call sites pass the
// provider's own values, so the generated wrapper stays identical on both
// paths, and settings.json itself stays usage-blind.
function applyStatusLineInjection(effective, providerName, providerId, settingsConfig, meta) {
  try {
    const instanceDir = join(INSTANCES_DIR, "claude", providerId);
    const wrapperPath = join(instanceDir, STATUSLINE_WRAPPER_FILENAME);
    const existing = effective.statusLine;
    // An explicit statusLine in the provider/common config is not a reason
    // to skip the injection — it becomes the wrapper's preferred relay
    // source (inlined at generation time), so deliberate configuration
    // keeps rendering while the provider tag is still added. Only a command
    // that IS the wrapper (a previous injection) relays nothing extra.
    let relayCommand: string | null = null;
    if (
      isPlainObject(existing) &&
      typeof existing.command === "string" && existing.command.trim() &&
      !existing.command.includes(STATUSLINE_WRAPPER_FILENAME)
    ) relayCommand = existing.command;
    mkdirSync(instanceDir, { recursive: true });
    // Tag color comes from the TUI preference file (fail-open "auto"). It is
    // inlined into the WRAPPER's content only — never into settings.json —
    // so the guard/baseline comparison of settings.json cannot see it and
    // prepare vs computeEffectiveSettings stay identical by construction.
    const colorCode = statuslineColorFor("claude", providerId);
    // Same channel for usage: resolved from the provider's own
    // settings_config + meta, inlined into the wrapper only. A throw here
    // (shouldn't happen — resolution is guarded) means no usage segment,
    // never a failed injection. Aggregation instances (loopback base URL +
    // live stack) take the per-member map instead of a single identity.
    let usageConfig: any = null;
    let stackConfig: any = null;
    try {
      const stack = isAggregationProviderSettings(settingsConfig) ? readStackState("claude") : null;
      if (stack) stackConfig = buildStackUsageConfig(stack, instanceDir, wrapperPath);
      if (!stackConfig) {
        usageConfig = buildUsageQueryConfig(
          resolveUsageIdentity(settingsConfig, meta),
          join(instanceDir, USAGE_CACHE_FILENAME),
          wrapperPath,
        );
      }
    } catch {}
    atomicWrite(wrapperPath, buildStatusLineWrapperScript(providerName, join(HOME, ".claude", "settings.json"), relayCommand, colorCode, usageConfig, stackConfig) + "\n");
    try { chmodSync(wrapperPath, 0o755); } catch {}
    // Keep display-related fields the user tuned (refreshInterval, padding)
    // when upgrading a previous injection; drop nothing else.
    effective.statusLine = {
      ...(isPlainObject(existing) ? existing : {}),
      type: "command",
      command: `${shQuote(process.execPath)} ${shQuote(wrapperPath)}`,
    };
  } catch {
    // best-effort: a failed injection leaves the config untouched — the
    // next launch retries. Never block a launch over a statusline.
  }
}

// Build an enabledPlugins patch from an instance's runtime settings. Explicit
// true/false both propagate (so /plugin enable AND disable survive the next
// launch); absent keys are omitted (json_patch leaves them untouched), so a
// stale instance can't delete a key another provider added.
function collectEnabledPluginsPatch(ep) {
  if (!isPlainObject(ep)) return null;
  const patch = {};
  for (const [k, v] of Object.entries(ep)) {
    if (v === true || v === false) patch[k] = v;
  }
  return Object.keys(patch).length ? patch : null;
}


